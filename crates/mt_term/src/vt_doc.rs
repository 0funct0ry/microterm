//! The VT conformance work list (`tests/vt_conformance.toml`): loaded by the `vt_conformance`
//! test and rendered into the generated "Terminal API (VT) support" page (`xtask gen-docs`).

use std::fmt::Write as _;

use serde::Deserialize;

/// Where the generated page lives, relative to the repository root.
pub const REFERENCE_DOC_PATH: &str = "site/src/content/docs/docs/reference/terminal-api.md";

const DATA: &str = include_str!("../tests/vt_conformance.toml");

/// One sequence of Ghostty's VT reference.
#[derive(Clone, Debug, Deserialize)]
pub struct Row {
    /// `Control`, `ESC`, `CSI` or `OSC`.
    pub kind: String,
    pub code: String,
    pub name: String,
    /// `supported`, `partial` or `unsupported`.
    pub status: String,
    #[serde(default)]
    pub notes: String,
    pub url: String,
    #[serde(default)]
    pub case: Vec<Case>,
}

/// Bytes to feed and what to assert afterwards; every `expect` field is optional.
#[derive(Clone, Debug, Default, Deserialize)]
pub struct Case {
    pub input: String,
    /// Exact bytes the terminal writes back.
    pub reply: Option<String>,
    /// Leading screen rows, trailing blanks trimmed.
    pub lines: Option<Vec<String>>,
    /// `[row, col]`, zero-based.
    pub cursor: Option<[usize; 2]>,
    pub cursor_shape: Option<String>,
    /// `bell`, `title:T`, `clipboard:T`, `notify:T`, `progress:State[:N]`, in order.
    pub events: Option<Vec<String>>,
    #[serde(default)]
    pub modes_on: Vec<String>,
    #[serde(default)]
    pub modes_off: Vec<String>,
    /// OSC 22 name (`""` = default).
    pub pointer: Option<String>,
    pub cwd: Option<String>,
    /// `terminal.osc_color_report` for this case.
    pub report: Option<String>,
    pub osc_notifications: Option<bool>,
    pub allow_shift_capture: Option<bool>,
}

#[derive(Deserialize)]
struct File {
    row: Vec<Row>,
}

/// Every row of the work list.
pub fn rows() -> Vec<Row> {
    toml::from_str::<File>(DATA)
        .expect("tests/vt_conformance.toml is valid")
        .row
}

/// The generated "Terminal API (VT) support" page.
pub fn reference_markdown() -> String {
    let rows = rows();
    let mut out = String::new();
    out.push_str(
        "---\ntitle: Terminal API (VT) support\ndescription: Every sequence in Ghostty's VT reference and whether microterm supports it.\n---\n\n",
    );
    out.push_str(
        "<!-- Generated by `cargo run -p xtask -- gen-docs` from crates/mt_term/tests/vt_conformance.toml. Do not edit. -->\n\n",
    );
    out.push_str(
        "microterm is checked against [Ghostty's VT reference](https://ghostty.org/docs/vt/reference) \
and its [external protocols](https://ghostty.org/docs/vt/external). Each row below is backed by test cases \
in `cargo test -p mt_term vt_conformance`.\n\n\
Status is **supported**, **partial** or **unsupported**; notes say what differs.\n",
    );
    let n = |s: &str| rows.iter().filter(|r| r.status == s).count();
    let _ = write!(
        out,
        "\n{} sequences: {} supported, {} partial, {} unsupported.\n",
        rows.len(),
        n("supported"),
        n("partial"),
        n("unsupported")
    );
    for (kind, title) in [
        ("Control", "Control characters"),
        ("ESC", "ESC sequences"),
        ("CSI", "CSI sequences"),
        ("OSC", "OSC sequences"),
    ] {
        let _ = write!(
            out,
            "\n## {title}\n\n| Sequence | Name | Status | Notes |\n|---|---|---|---|\n"
        );
        for r in rows.iter().filter(|r| r.kind == kind) {
            let notes = r.notes.replace('|', "\\|");
            let _ = writeln!(
                out,
                "| `{}` | [{}]({}) | {} | {} |",
                r.code.replace('|', "\\|"),
                r.name,
                r.url,
                r.status,
                notes
            );
        }
    }
    out.push_str(
        "\n## See also\n\n- [Mouse & selection](/docs/mouse-and-selection/) for XTSHIFTESCAPE and the pointer shape.\n- [Notifications & status](/docs/notifications-and-status/) for OSC 9 and OSC 9;4.\n- [Config file](/docs/config-file/) for the `[terminal]` keys.\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn work_list_parses_and_has_valid_statuses() {
        let rows = rows();
        assert!(rows.len() > 60);
        for r in &rows {
            assert!(
                matches!(r.status.as_str(), "supported" | "partial" | "unsupported"),
                "{}",
                r.code
            );
            assert!(matches!(r.kind.as_str(), "Control" | "ESC" | "CSI" | "OSC"));
            if r.status == "unsupported" {
                assert!(!r.notes.is_empty(), "{} needs a reason", r.code);
            } else {
                assert!(!r.case.is_empty(), "{} has no test case", r.code);
            }
        }
    }

    #[test]
    fn generated_page_matches_the_committed_file() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(REFERENCE_DOC_PATH);
        let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
        assert_eq!(
            on_disk,
            reference_markdown(),
            "stale {REFERENCE_DOC_PATH}: run `cargo run -p xtask -- gen-docs`"
        );
    }
}
